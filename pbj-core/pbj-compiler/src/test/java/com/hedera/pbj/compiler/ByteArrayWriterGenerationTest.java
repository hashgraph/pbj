package com.hedera.pbj.compiler;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.hedera.pbj.compiler.impl.PerformanceOptions;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Set;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** Generated writers and sizes call nested generated code directly only when it is generated in the same build. */
class ByteArrayWriterGenerationTest {
    @TempDir
    Path directory;

    @Test
    void nestedMessagesFromDependenciesKeepTheCodecInstanceCall() throws Exception {
        final Path sources = Files.createDirectories(directory.resolve("src"));
        final Path dependencies = Files.createDirectories(directory.resolve("dep"));
        final Path dependency = dependencies.resolve("dep.proto");
        Files.writeString(dependency, """
                syntax = "proto3";
                package dep;
                message External { int64 a = 1; }
                """);
        final Path proto = sources.resolve("local.proto");
        Files.writeString(proto, """
                syntax = "proto3";
                package local;
                import "dep.proto";
                message Local { int64 a = 1; }
                message Holder {
                    Local local = 1;
                    dep.External external = 2;
                    repeated Local locals = 3;
                    repeated dep.External externals = 4;
                    oneof choice { Local local_choice = 5; dep.External external_choice = 6; }
                }
                """);
        final Path out = directory.resolve("out");
        PbjCompiler.compileFilesIn(
                List.of(proto.toFile()),
                List.of(dependency.toFile()),
                Set.of(sources.toFile(), dependencies.toFile()),
                out.toFile(),
                out.toFile(),
                null,
                false,
                false,
                Set.of(),
                Set.of(),
                PerformanceOptions.NONE);
        final String codec = Files.readString(out.resolve("local/codec/HolderProtoCodec.java"));
        final String writer = codec.substring(
                codec.indexOf("public static int writeTo("), codec.indexOf("public int measureRecord("));
        // generated in this build: direct static calls, for singular, repeated and oneof fields
        assertTrue(writer.contains("local.codec.LocalProtoCodec.writeTo(local, output"), writer);
        assertTrue(writer.contains("local.codec.LocalProtoCodec.writeTo(item, output"), writer);
        assertTrue(writer.contains("local.codec.LocalProtoCodec.writeTo(localChoice, output"), writer);
        // from a dependency, which may have been generated by another PBJ version: the Codec instance
        assertTrue(writer.contains("writeMessage(output, offset, HolderSchema.EXTERNAL,"), writer);
        assertTrue(writer.contains("writeMessageList(output, offset, HolderSchema.EXTERNALS,"), writer);
        assertTrue(writer.contains("writeMessage(output, offset, HolderSchema.EXTERNAL_CHOICE,"), writer);
        assertFalse(writer.contains("ExternalProtoCodec.writeTo"), writer);
        // the oneof is a switch on its kind
        assertTrue(writer.contains("switch (data.choice().kind())"), writer);

        // the stream writer follows the same rule
        final String stream = codec.substring(
                codec.indexOf("public static void writeTo("), codec.indexOf("public static int writeTo("));
        assertTrue(stream.contains("local.codec.LocalProtoCodec.writeTo(local, out)"), stream);
        assertTrue(stream.contains("local.codec.LocalProtoCodec.writeTo(item, out)"), stream);
        assertTrue(stream.contains("writeMessage(out, HolderSchema.EXTERNAL,"), stream);
        assertFalse(stream.contains("ExternalProtoCodec.writeTo"), stream);

        // the parser too: nested codecs from this build are called directly, dependencies through their Codec
        final String parser = codec.substring(codec.indexOf("public static @NonNull Holder parseFrom("));
        assertTrue(parser.contains("local.codec.LocalProtoCodec.parseFrom(input, strictMode"), parser);
        assertTrue(parser.contains("External.PROTOBUF.parse(input, strictMode"), parser);
        assertFalse(parser.contains("ExternalProtoCodec.parseFrom"), parser);

        // and so does protobufSize(): nested models from this build are measured directly
        final String model = Files.readString(out.resolve("local/Holder.java"));
        final String size = model.substring(model.indexOf("public int protobufSize()"));
        assertTrue(size.contains("final int size = local.protobufSize();"), size);
        assertTrue(size.contains("sizeOfMessage(HolderSchema.EXTERNAL,"), size);
        assertTrue(size.contains("switch (choice().kind())"), size);
    }
}
