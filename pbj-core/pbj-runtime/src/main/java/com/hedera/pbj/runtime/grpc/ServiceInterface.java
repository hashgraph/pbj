package com.hedera.pbj.runtime.grpc;

import com.hedera.pbj.runtime.io.buffer.Bytes;
import edu.umd.cs.findbugs.annotations.NonNull;
import java.net.SocketAddress;
import java.security.cert.Certificate;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * Defines a common interface for all implementations of a gRPC {@code service}. PBJ will generate a sub-interface
 * for each {@code service} in the protobuf schema definition files, with default implementations of each of the
 * given methods in this interface.
 *
 * <p>For example, suppose I have the following protobuf file:
 * <pre>
 * {@code
 * package example;
 *
 * service HelloService {
 *   rpc SayHello (HelloRequest) returns (HelloResponse);
 * }
 *
 * message HelloRequest {
 *   string greeting = 1;
 * }
 *
 * message HelloResponse {
 *   string reply = 1;
 * }
 * }
 * </pre>
 *
 * <p>From this file, PBJ will generate a {@code HelloService} interface that extends {@code ServiceInterface}:
 * <pre>
 * {@code
 * public interface HelloService extends ServiceInterface {
 *    // ...
 *
 *    @NonNull
 *    HelloResponse sayHello(final @NonNull HelloRequest request);
 *
 *    default String serviceName() { return "HelloService"; }
 *    default String fullName() { return "example.HelloService"; }
 *
 *    // ...
 * }
 * }
 * </pre>
 *
 * In the application code, you will simply create a new class implementing the {@code HelloService} interface, and
 * register it with your webserver in whatever way is appropriate for your webserver.
 */
public interface ServiceInterface extends AutoCloseable {
    /** The kind of a gRPC method, determined by whether the request and the reply are streams. */
    enum MethodType {
        /** The type is not known, for example because the service was generated by an older version of PBJ. */
        UNKNOWN,
        /** A single request and a single reply. */
        UNARY,
        /** A stream of requests and a single reply. */
        CLIENT_STREAMING,
        /** A single request and a stream of replies. */
        SERVER_STREAMING,
        /** A stream of requests and a stream of replies. */
        BIDI_STREAMING
    }

    /** Represents the metadata of a method in a gRPC service. */
    interface Method {
        String name();

        /**
         * Gets the kind of this method. Transports that cannot support every kind of method, such as gRPC-Web which
         * has no client streaming, use this to reject calls they cannot serve.
         *
         * @return the kind of this method, or {@link MethodType#UNKNOWN} if not known
         */
        default MethodType type() {
            return MethodType.UNKNOWN;
        }
    }

    /** The options that are passed to the service when a new connection is opened. */
    interface RequestOptions {
        /** A constant for the gRPC content type "application/grpc". */
        String APPLICATION_GRPC = "application/grpc";
        /** A constant for the gRPC content type "application/grpc+proto". */
        String APPLICATION_GRPC_PROTO = "application/grpc+proto";
        /** A constant for the gRPC content type "application/grpc+json". */
        String APPLICATION_GRPC_JSON = "application/grpc+json";
        /** A constant for the gRPC-Web content type "application/grpc-web". */
        String APPLICATION_GRPC_WEB = "application/grpc-web";
        /** A constant for the gRPC-Web content type "application/grpc-web+proto". */
        String APPLICATION_GRPC_WEB_PROTO = "application/grpc-web+proto";
        /** A constant for the gRPC-Web content type "application/grpc-web+json". */
        String APPLICATION_GRPC_WEB_JSON = "application/grpc-web+json";
        /** A constant for the base64 encoded gRPC-Web content type "application/grpc-web-text". */
        String APPLICATION_GRPC_WEB_TEXT = "application/grpc-web-text";
        /** A constant for the base64 encoded gRPC-Web content type "application/grpc-web-text+proto". */
        String APPLICATION_GRPC_WEB_TEXT_PROTO = "application/grpc-web-text+proto";
        /** Base64-encoded gRPC-Web JSON. */
        String APPLICATION_GRPC_WEB_TEXT_JSON = "application/grpc-web-text+json";

        /**
         * Default maximum message size in bytes ({@value}).
         *
         * @see #maxMessageSizeBytes()
         */
        int DEFAULT_MAX_MESSAGE_SIZE_BYTES = 1024 * 10; // 10KB

        /**
         * The authority of the client that is connecting to the service. This is the value of the ":authority" header
         * in the HTTP/2 request. This value is used by the service to determine the client's identity. It may be that
         * no authority is provided, in which case this method will return an empty optional.
         *
         * @return the authority of the client
         */
        @NonNull
        Optional<String> authority();

        /**
         * Gets whether the content type describes a protobuf message. This will be true if the {@link #contentType()}
         * is equal to {@link #APPLICATION_GRPC_PROTO} or {@link #APPLICATION_GRPC}, or to one of the gRPC-Web
         * protobuf content types {@link #APPLICATION_GRPC_WEB}, {@link #APPLICATION_GRPC_WEB_PROTO},
         * {@link #APPLICATION_GRPC_WEB_TEXT} or {@link #APPLICATION_GRPC_WEB_TEXT_PROTO}.
         */
        default boolean isProtobuf() {
            final String contentType = contentType();
            if (contentType == null) {
                return false;
            }
            return switch (contentType) {
                case APPLICATION_GRPC_PROTO,
                        APPLICATION_GRPC,
                        APPLICATION_GRPC_WEB,
                        APPLICATION_GRPC_WEB_PROTO,
                        APPLICATION_GRPC_WEB_TEXT,
                        APPLICATION_GRPC_WEB_TEXT_PROTO -> true;
                default -> false;
            };
        }

        /**
         * Gets whether the content type describes a JSON message. This will be true if the {@link #contentType()}
         * is equal to {@link #APPLICATION_GRPC_JSON}, {@link #APPLICATION_GRPC_WEB_JSON}, or
         * {@link #APPLICATION_GRPC_WEB_TEXT_JSON}.
         */
        default boolean isJson() {
            return APPLICATION_GRPC_JSON.equals(contentType())
                    || APPLICATION_GRPC_WEB_JSON.equals(contentType())
                    || APPLICATION_GRPC_WEB_TEXT_JSON.equals(contentType());
        }

        /**
         * Gets the content type of the request. This is the value of the "content-type" header in the HTTP/2 request.
         * This value is used by the service to determine how to parse the request. Since gRPC supports custom content
         * types, it is possible that the content type will be something other than the constants defined in this
         * interface.
         *
         * @return the content type of the request
         */
        @NonNull
        String contentType();

        /**
         * Maximum size of any message in bytes. Defaults to {@value #DEFAULT_MAX_MESSAGE_SIZE_BYTES}.
         *
         * @return the maximum number of bytes a single message can be
         */
        default int maxMessageSizeBytes() {
            return DEFAULT_MAX_MESSAGE_SIZE_BYTES;
        }

        /**
         * Metadata associated with a request. Key names MUST NOT start with "grpc-" prefix. The metadata is sent
         * via HTTP2 headers, and the total size of the headers, both system and these custom metadata headers,
         * is often limited by 8KB. So the metadata mechanism is only suited for passing samll amounts of data.
         * Also, in HTTP2, header names are usually all-lower-case, so it's strongly recommended to use lower-case
         * key names in this map.
         * <p>
         * A client application can implement this method in a RequestOptions object that it passes to a client
         * stub constructor, e.g. the GreeterInterface.GreeterClient, or its service call methods that accept
         * the additional RequestOptions argument.
         * <p>
         * A server application can access the client's metadata using the RequestOptions parameter passed to the
         * ServiceInterface stub methods.
         *
         * @return an immutable, non-null, but possibly empty Map to access metadata values using their keys
         */
        default Map<String, String> metadata() {
            return Map.of();
        }

        /// The `SocketAddress` of the remote peer, or null if unknown or undefined.
        default SocketAddress remoteAddress() {
            return null;
        }

        /// The TLS certificate chain of the remote peer, or empty if unknown, undefined, or the connection isn't TLS.
        default Optional<Certificate[]> remoteCertificateChain() {
            return Optional.empty();
        }
    }

    /** Gets the simple name of the service. For example, "HelloService". */
    @NonNull
    String serviceName();
    /** Gets the full name of the service. For example, "example.HelloService". */
    @NonNull
    String fullName();
    /** Gets a list of each method in the service. This list may be empty but should never be null. */
    @NonNull
    List<Method> methods();

    /**
     * Called by the webserver to open a new connection between the client and the service. This method may be called
     * many times concurrently, once per connection. The implementation must therefore be thread-safe. A default
     * implementation is provided by the generated PBJ code, which will handle the dispatching of messages to the
     * appropriate methods in the correct way (unary, server-side streaming, etc.).
     *
     * @param method The method that was called by the client.
     * @param opts Any options from the request, such as the content type.
     * @param responses The subscriber used by the service to push responses back to the client.
     */
    @NonNull
    Pipeline<? super Bytes> open(
            @NonNull Method method, @NonNull RequestOptions opts, @NonNull Pipeline<? super Bytes> responses)
            throws GrpcException;

    /**
     * Closes this ServiceInterface instance releasing all resources, such as open network connections etc.
     */
    default void close() {}
}
