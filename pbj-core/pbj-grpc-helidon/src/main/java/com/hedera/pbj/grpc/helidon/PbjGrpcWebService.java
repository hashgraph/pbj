/**
 * Serves a PBJ {@link ServiceInterface} over <a href="https://github.com/grpc/grpc/blob/master/doc/PROTOCOL-WEB.md">
 * gRPC-Web</a>, so that browsers can call it.
 *
 * <p>Browsers cannot speak native gRPC because they cannot read HTTP trailers. gRPC-Web uses the same length-prefixed
 * messages, but sends the trailers as a final frame in the response body, flagged {@code 0x80}. It works over both
 * HTTP/1.1 and HTTP/2, so this class is a Helidon {@link HttpService} registered on the {@code HttpRouting}, next to
 * the native gRPC {@link PbjRouting} on the same port:
 *
 * <pre>{@code
 * WebServer.builder()
 *         .port(8080)
 *         .addRouting(PbjRouting.builder().service(service))
 *         .addRouting(HttpRouting.builder().register(PbjGrpcWebService.of(service)))
 *         .build()
 *         .start();
 * }</pre>
 *
 * <p>Supported:
 * <ul>
 *     <li>Unary and server-streaming methods. gRPC-Web has no client streaming, so client-streaming and bidirectional
 *     methods fail with {@link GrpcStatus#UNIMPLEMENTED}. Methods whose {@link ServiceInterface.MethodType} is
 *     {@link ServiceInterface.MethodType#UNKNOWN}, which is the case for services generated by older versions of PBJ,
 *     are served on a best-effort basis: all request messages are read from the request body before the call is
 *     half-closed.</li>
 *     <li>Binary ({@code application/grpc-web}, {@code +proto}, {@code +json}) and base64 text
 *     ({@code application/grpc-web-text}, {@code +proto}) modes.</li>
 *     <li>Message compression ({@code grpc-encoding} and {@code grpc-accept-encoding}).</li>
 *     <li>Deadlines ({@code grpc-timeout}). The deadline is checked once the request body has been read, and while
 *     waiting for replies.</li>
 *     <li>CORS for an allowlist of origins, see {@link Builder#allowedOrigins(String...)}. Without an allowlist no CORS
 *     headers are sent, so only same-origin pages and non-browser clients can call the service.</li>
 * </ul>
 *
 * <p>Each call blocks its (virtual) request thread until the service completes the call, because Helidon finishes
 * the response once the handler returns.
 */
public final class PbjGrpcWebService implements HttpService {
    private static final System.Logger LOGGER = System.getLogger(PbjGrpcWebService.class.getName());

    /** The request headers browsers are allowed to send by default, see {@link Builder#allowedHeaders}. */
    public static final List<String> DEFAULT_ALLOWED_HEADERS =
            List.of("content-type", "x-grpc-web", "x-user-agent", "grpc-timeout");

    /** Allows any origin when passed to {@link Builder#allowedOrigins(String...)}. */
    public static final String ANY_ORIGIN = "*";

    /** The response headers browser code may read. */
    private static final String EXPOSED_HEADERS = "grpc-status, grpc-message";

    private static final String ALLOWED_METHODS = "POST, OPTIONS";

    /** How long browsers may cache a preflight response, in seconds. */
    private static final String PREFLIGHT_MAX_AGE = "86400";

    private static final int READ_BUFFER_SIZE = 8192;

    private final ServiceInterface service;
    private final PbjGrpcServiceConfig serviceConfig;
    private final int maxMessageSizeBytes;
    private final Set<String> allowedOrigins;
    private final String allowedHeaders;

    private PbjGrpcWebService(@NonNull final Builder builder) {
        this.service = builder.service;
        this.serviceConfig = builder.serviceConfig;
        this.maxMessageSizeBytes = builder.maxMessageSizeBytes;
        this.allowedOrigins = Set.copyOf(builder.allowedOrigins);
        this.allowedHeaders = String.join(", ", builder.allowedHeaders);
    }

    /**
     * Create a gRPC-Web service with the default configuration, which allows no cross-origin requests.
     *
     * @param service the service to expose
     * @return the gRPC-Web service, to be registered on an {@code HttpRouting}
     */
    @NonNull
    public static PbjGrpcWebService of(@NonNull final ServiceInterface service) {
        return builder(service).build();
    }

    /**
     * Create a builder for a gRPC-Web service.
     *
     * @param service the service to expose
     * @return a new builder
     */
    @NonNull
    public static Builder builder(@NonNull final ServiceInterface service) {
        return new Builder(service);
    }

    @Override
    public void routing(@NonNull final HttpRules rules) {
        for (final ServiceInterface.Method method : service.methods()) {
            final var route = new PbjMethodRoute(service, serviceConfig, method);
            final var path = "/" + service.fullName() + "/" + method.name();
            rules.post(path, (req, res) -> new Call(route, req, res).handle());
            rules.options(path, this::preflight);
        }
    }

    /** Answers a CORS preflight request. */
    private void preflight(@NonNull final ServerRequest req, @NonNull final ServerResponse res) {
        final var origin = req.headers().first(HeaderNames.ORIGIN);
        if (origin.isEmpty() || !isAllowedOrigin(origin.get())) {
            res.status(Status.FORBIDDEN_403).send();
            return;
        }
        addCorsHeaders(origin.get(), res);
        res.header(HeaderNames.ACCESS_CONTROL_ALLOW_METHODS, ALLOWED_METHODS);
        res.header(HeaderNames.ACCESS_CONTROL_ALLOW_HEADERS, allowedHeaders);
        res.header(HeaderNames.ACCESS_CONTROL_MAX_AGE, PREFLIGHT_MAX_AGE);
        res.status(Status.NO_CONTENT_204).send();
    }

    private boolean isAllowedOrigin(@NonNull final String origin) {
        return allowedOrigins.contains(ANY_ORIGIN) || allowedOrigins.contains(origin);
    }

    private void addCorsHeaders(@NonNull final String origin, @NonNull final ServerResponse res) {
        if (allowedOrigins.contains(ANY_ORIGIN)) {
            res.header(HeaderNames.ACCESS_CONTROL_ALLOW_ORIGIN, ANY_ORIGIN);
        } else {
            res.header(HeaderNames.ACCESS_CONTROL_ALLOW_ORIGIN, origin);
            res.header(HeaderNames.VARY, HeaderNames.ORIGIN.defaultCase());
        }
        res.header(HeaderNames.ACCESS_CONTROL_EXPOSE_HEADERS, EXPOSED_HEADERS);
    }

    /**
     * A single gRPC-Web call. It reads the request on the request thread, receives replies from the service on any
     * thread, and writes the response under a lock.
     */
    private final class Call implements Pipeline<Bytes> {
        private final PbjMethodRoute route;
        private final ServerRequest req;
        private final ServerResponse res;

        /** Guards every write to {@link #res}, since the service may reply from any thread. */
        private final ReentrantLock lock = new ReentrantLock();

        /** Released once the service has completed the call, successfully or not. */
        private final CountDownLatch done = new CountDownLatch(1);

        private boolean textMode;
        private String contentType = APPLICATION_GRPC_WEB_PROTO;
        private String outgoingEncoding = GrpcCompression.IDENTITY;

        /** The output stream of the response, opened when the first message is sent. Guarded by {@link #lock}. */
        private OutputStream out;

        /** Whether the call has completed. No messages may be sent once it has. Guarded by {@link #lock}. */
        private boolean completed;

        private Status httpStatus = Status.OK_200;
        private GrpcStatus grpcStatus = GrpcStatus.OK;
        private String grpcMessage;

        Call(@NonNull final PbjMethodRoute route, @NonNull final ServerRequest req, @NonNull final ServerResponse res) {
            this.route = route;
            this.req = req;
            this.res = res;
        }

        /** Handles the call on the request thread, returning once the response is complete. */
        void handle() {
            route.requestCounter().increment();
            req.headers()
                    .first(HeaderNames.ORIGIN)
                    .filter(PbjGrpcWebService.this::isAllowedOrigin)
                    .ifPresent(origin -> addCorsHeaders(origin, res));

            final Pipeline<? super Bytes> requests;
            final long deadline;
            final GrpcCompression.Decompressor decompressor;
            try {
                contentType = negotiateContentType();
                final var methodType = route.method().type();
                if (methodType == ServiceInterface.MethodType.CLIENT_STREAMING
                        || methodType == ServiceInterface.MethodType.BIDI_STREAMING) {
                    throw new GrpcException(
                            GrpcStatus.UNIMPLEMENTED,
                            "gRPC-Web does not support client streaming method "
                                    + route.method().name());
                }
                decompressor = negotiateDecompressor();
                outgoingEncoding = GrpcCompression.determineCompressorName(
                        headerValues(GrpcHeaders.GRPC_ACCEPT_ENCODING), serviceConfig.encoding());
                deadline = deadline();
                requests = route.service().open(route.method(), options(), this);
            } catch (final GrpcException e) {
                route.failedGrpcRequestCounter().increment();
                complete(e.status(), e.getMessage());
                finishResponse();
                return;
            } catch (final UnsupportedContentTypeException e) {
                route.failedHttpRequestCounter().increment();
                httpStatus = Status.UNSUPPORTED_MEDIA_TYPE_415;
                complete(GrpcStatus.INVALID_ARGUMENT, e.getMessage());
                finishResponse();
                return;
            } catch (final RuntimeException e) {
                route.failedUnknownRequestCounter().increment();
                LOGGER.log(INFO, "Failed to initialize grpc-web call", e);
                complete(GrpcStatus.UNKNOWN, null);
                finishResponse();
                return;
            }

            try {
                readRequests(requests, decompressor);
                requests.clientEndStreamReceived();
                awaitCompletion(requests, deadline);
            } catch (final InterruptedException e) {
                Thread.currentThread().interrupt();
                fail(requests, new GrpcException(GrpcStatus.CANCELLED, e));
            } catch (final Exception e) {
                fail(requests, e);
            } finally {
                finishResponse();
            }
        }

        /**
         * Fails the call. If the service has not completed the call already, for example because the request could not
         * be read, the status is taken from the exception. The service is then told about the error so that it can
         * tear down its resources.
         */
        private void fail(@NonNull final Pipeline<? super Bytes> requests, @NonNull final Exception e) {
            if (e instanceof GrpcException grpcException) {
                complete(grpcException.status(), grpcException.getMessage());
            } else {
                complete(GrpcStatus.INTERNAL, null);
            }
            try {
                requests.onError(e);
            } catch (final RuntimeException onErrorFailure) {
                LOGGER.log(DEBUG, "Service failed to handle an error for " + route.method(), onErrorFailure);
            }
        }

        /** Reads all messages from the request body and passes them to the service. */
        private void readRequests(
                @NonNull final Pipeline<? super Bytes> requests,
                @NonNull final GrpcCompression.Decompressor decompressor)
                throws IOException {
            final var deframer = new GrpcDeframer(maxMessageSizeBytes, decompressor, requests::onNext);
            final var base64 = textMode ? new Base64ChunkDecoder() : null;
            final byte[] buffer = new byte[READ_BUFFER_SIZE];
            try (InputStream in = req.content().inputStream()) {
                int read;
                while (!isCompleted() && (read = in.read(buffer)) != -1) {
                    if (base64 == null) {
                        deframer.add(buffer, 0, read);
                    } else {
                        final byte[] decoded = base64.decode(buffer, 0, read);
                        deframer.add(decoded, 0, decoded.length);
                    }
                }
            }
            if (base64 != null && !isCompleted()) {
                base64.finish();
            }
        }

        /** Waits for the service to complete the call, failing it if the deadline passes first. */
        private void awaitCompletion(@NonNull final Pipeline<? super Bytes> requests, final long deadline)
                throws InterruptedException {
            if (deadline == Long.MAX_VALUE) {
                done.await();
            } else if (!done.await(deadline - System.nanoTime(), TimeUnit.NANOSECONDS)) {
                route.deadlineExceededCounter().increment();
                fail(requests, new GrpcException(GrpcStatus.DEADLINE_EXCEEDED));
            }
        }

        @NonNull
        private String negotiateContentType() throws UnsupportedContentTypeException {
            final var requestContentType = req.headers().contentType();
            final var ct = requestContentType.isEmpty()
                    ? ""
                    : requestContentType.get().mediaType().text();
            if (ct.startsWith(APPLICATION_GRPC_WEB_TEXT)) {
                textMode = true;
                return APPLICATION_GRPC_WEB_TEXT.equals(ct) ? APPLICATION_GRPC_WEB_TEXT_PROTO : ct;
            }
            if (ct.startsWith(APPLICATION_GRPC_WEB)) {
                return APPLICATION_GRPC_WEB.equals(ct) ? APPLICATION_GRPC_WEB_PROTO : ct;
            }
            throw new UnsupportedContentTypeException("invalid gRPC-Web request content-type \"" + ct + "\"");
        }

        @NonNull
        private GrpcCompression.Decompressor negotiateDecompressor() {
            final var encodings = req.headers().contains(GrpcHeaders.GRPC_ENCODING)
                    ? headerValues(GrpcHeaders.GRPC_ENCODING)
                    : List.of(GrpcCompression.IDENTITY);
            try {
                return GrpcCompression.determineDecompressor(encodings);
            } catch (final IllegalStateException e) {
                throw new GrpcException(
                        GrpcStatus.UNIMPLEMENTED,
                        "Decompressor is not installed for grpc-encoding \"" + String.join(", ", encodings) + "\"",
                        e);
            }
        }

        @NonNull
        private List<String> headerValues(@NonNull final HeaderName name) {
            return req.headers().contains(name) ? req.headers().get(name).allValues(true) : List.of();
        }

        /**
         * Gets the {@link System#nanoTime()} by which the call must complete, from the {@code grpc-timeout} header.
         * Returns {@link Long#MAX_VALUE} if there is no deadline, or the header is invalid.
         */
        private long deadline() {
            final var timeout = req.headers().first(GrpcHeaders.GRPC_TIMEOUT);
            if (timeout.isEmpty()) {
                return Long.MAX_VALUE;
            }
            final var timeoutNanos = GrpcTimeout.parseNanos(timeout.get());
            return timeoutNanos.isPresent() ? System.nanoTime() + timeoutNanos.getAsLong() : Long.MAX_VALUE;
        }

        @NonNull
        private ServiceInterface.RequestOptions options() {
            // Metadata, aka additional headers, provided by the client with the request.
            final Map<String, String> metadata = req.headers().stream()
                    .filter(header -> !header.name().toLowerCase().startsWith("grpc-"))
                    .collect(Collectors.toUnmodifiableMap(Header::name, Header::values));
            return new GrpcRequestOptions(
                    Optional.ofNullable(req.authority()),
                    contentType,
                    maxMessageSizeBytes,
                    metadata,
                    req.remotePeer().address(),
                    req.remotePeer().tlsCertificates());
        }

        private boolean isCompleted() {
            lock.lock();
            try {
                return completed;
            } finally {
                lock.unlock();
            }
        }

        /** Records the final status of the call, unless it was already completed, and releases the request thread. */
        private void complete(@NonNull final GrpcStatus status, @Nullable final String message) {
            lock.lock();
            try {
                if (!completed) {
                    completed = true;
                    grpcStatus = status;
                    grpcMessage = message;
                }
            } finally {
                lock.unlock();
            }
            done.countDown();
        }

        /**
         * Writes the end of the response. If no message was sent, the status goes in the HTTP headers
         * ("Trailers-Only"). Otherwise, it goes in a final frame flagged {@link GrpcFramer#TRAILERS_FLAG}.
         */
        private void finishResponse() {
            lock.lock();
            try {
                if (out == null) {
                    res.status(httpStatus);
                    res.header(HeaderNames.CONTENT_TYPE, contentType);
                    res.header(GrpcHeaders.header(grpcStatus));
                    if (grpcMessage != null) {
                        res.header(GrpcHeaders.GRPC_MESSAGE, UriEncoding.encodeUri(grpcMessage));
                    }
                    res.send();
                } else {
                    final var trailers = new StringBuilder()
                            .append("grpc-status: ")
                            .append(grpcStatus.ordinal())
                            .append("\r\n");
                    if (grpcMessage != null) {
                        trailers.append("grpc-message: ")
                                .append(UriEncoding.encodeUri(grpcMessage))
                                .append("\r\n");
                    }
                    final var payload = Bytes.wrap(trailers.toString().getBytes(StandardCharsets.US_ASCII));
                    writeFrame(GrpcFramer.frame(GrpcFramer.TRAILERS_FLAG, payload));
                    out.close();
                }
            } catch (final IOException | RuntimeException e) {
                // The client has most likely gone away. There is nothing left to tell it.
                LOGGER.log(DEBUG, "Failed to finish grpc-web response: " + route.method(), e);
            } finally {
                lock.unlock();
            }
        }

        /** Writes a frame to the response body, base64 encoding it in text mode, and flushes it to the client. */
        private void writeFrame(@NonNull final byte[] frame) throws IOException {
            out.write(textMode ? Base64.getEncoder().encode(frame) : frame);
            out.flush();
        }

        @Override
        public void onSubscribe(@NonNull final Flow.Subscription subscription) {
            // FUTURE: Add support for flow control. For now, a slow client slows down the thread calling onNext.
            subscription.request(Long.MAX_VALUE);
        }

        @Override
        public void onNext(@NonNull final Bytes reply) {
            lock.lock();
            try {
                if (completed) {
                    throw new IllegalStateException("The call has already completed");
                }
                if (out == null) {
                    res.status(Status.OK_200);
                    res.header(HeaderNames.CONTENT_TYPE, contentType);
                    res.header(GrpcHeaders.GRPC_ENCODING, outgoingEncoding);
                    res.header(
                            GrpcHeaders.GRPC_ACCEPT_ENCODING,
                            serviceConfig.acceptEncodings().isEmpty()
                                    ? GrpcCompression.IDENTITY
                                    : String.join(",", serviceConfig.acceptEncodings()));
                    out = res.outputStream();
                }
                writeFrame(GrpcFramer.frameMessage(reply, outgoingEncoding));
            } catch (final IOException e) {
                failedResponse(e);
                throw new UncheckedIOException(e);
            } catch (final RuntimeException e) {
                failedResponse(e);
                throw e;
            } finally {
                lock.unlock();
            }
        }

        private void failedResponse(@NonNull final Exception e) {
            LOGGER.log(DEBUG, "Failed to respond to grpc-web request: " + route.method(), e);
            route.failedResponseCounter().increment();
        }

        @Override
        public void onError(@NonNull final Throwable throwable) {
            if (throwable instanceof final GrpcException grpcException) {
                complete(grpcException.status(), grpcException.getMessage());
            } else {
                LOGGER.log(DEBUG, "Failed to send response", throwable);
                complete(GrpcStatus.INTERNAL, null);
            }
        }

        @Override
        public void onComplete() {
            complete(GrpcStatus.OK, null);
        }

        @Override
        public void closeConnection() {
            complete(GrpcStatus.CANCELLED, null);
        }
    }

    /** Thrown when the request content type is not a gRPC-Web content type. */
    private static final class UnsupportedContentTypeException extends Exception {
        UnsupportedContentTypeException(@NonNull final String message) {
            super(message);
        }
    }

    /** Fluent API builder for {@link PbjGrpcWebService}. */
    public static final class Builder implements io.helidon.common.Builder<Builder, PbjGrpcWebService> {
        private final ServiceInterface service;
        private PbjGrpcServiceConfig serviceConfig = PbjGrpcServiceConfig.DEFAULT;
        private int maxMessageSizeBytes = ServiceInterface.RequestOptions.DEFAULT_MAX_MESSAGE_SIZE_BYTES;
        private final Set<String> allowedOrigins = new LinkedHashSet<>();
        private final Set<String> allowedHeaders = new LinkedHashSet<>(DEFAULT_ALLOWED_HEADERS);

        private Builder(@NonNull final ServiceInterface service) {
            this.service = requireNonNull(service);
        }

        /**
         * Sets the compression configuration, as for native gRPC. Defaults to {@link PbjGrpcServiceConfig#DEFAULT}.
         *
         * @param serviceConfig the service configuration
         * @return this builder
         */
        @NonNull
        public Builder serviceConfig(@NonNull final PbjGrpcServiceConfig serviceConfig) {
            this.serviceConfig = requireNonNull(serviceConfig);
            return this;
        }

        /**
         * Sets the maximum size of a single request message. Defaults to
         * {@link ServiceInterface.RequestOptions#DEFAULT_MAX_MESSAGE_SIZE_BYTES}. Use the same value as the native
         * gRPC {@link PbjConfig}, see {@link #config(PbjConfig)}.
         *
         * @param maxMessageSizeBytes the maximum message size in bytes
         * @return this builder
         */
        @NonNull
        public Builder maxMessageSizeBytes(final int maxMessageSizeBytes) {
            if (maxMessageSizeBytes <= 0) {
                throw new IllegalArgumentException("maxMessageSizeBytes must be positive");
            }
            this.maxMessageSizeBytes = maxMessageSizeBytes;
            return this;
        }

        /**
         * Takes the settings shared with native gRPC, such as the maximum message size, from the PBJ protocol
         * configuration of the server.
         *
         * @param config the PBJ protocol configuration
         * @return this builder
         */
        @NonNull
        public Builder config(@NonNull final PbjConfig config) {
            return maxMessageSizeBytes(config.maxMessageSizeBytes());
        }

        /**
         * Adds origins, such as {@code "https://example.com"}, that browsers may call the service from. Use
         * {@link #ANY_ORIGIN} to allow any origin. By default, no cross-origin calls are allowed.
         *
         * @param origins the origins to allow
         * @return this builder
         */
        @NonNull
        public Builder allowedOrigins(@NonNull final String... origins) {
            for (final String origin : origins) {
                allowedOrigins.add(requireNonNull(origin));
            }
            return this;
        }

        /**
         * Adds request headers that browsers may send on cross-origin calls, in addition to
         * {@link #DEFAULT_ALLOWED_HEADERS}. Custom metadata headers must be added here.
         *
         * @param headers the header names to allow
         * @return this builder
         */
        @NonNull
        public Builder allowedHeaders(@NonNull final String... headers) {
            for (final String header : headers) {
                allowedHeaders.add(requireNonNull(header).toLowerCase());
            }
            return this;
        }

        @Override
        @NonNull
        public PbjGrpcWebService build() {
            return new PbjGrpcWebService(this);
        }
    }
}
